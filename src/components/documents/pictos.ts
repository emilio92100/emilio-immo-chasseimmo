const rond = (cx: number, cy: number, r: number) => `M${cx - r} ${cy}a${r} ${r} 0 1 0 ${2 * r} 0a${r} ${r} 0 1 0 ${-2 * r} 0`;

/* L'exposition : une flèche dans un cercle, tournée vers le point cardinal
   (0° : le nord, en haut ; on tourne dans le sens des aiguilles). */
const vers = (deg: number): string[] => {
  const r = (deg * Math.PI) / 180;
  const f = (n: number) => Math.round(n * 100) / 100;
  const dx = Math.sin(r), dy = -Math.cos(r);
  const tx = 12 + dx * 5.4, ty = 12 + dy * 5.4;
  const bout = (a: number) => `${f(tx + Math.sin(a) * 3.4)} ${f(ty - Math.cos(a) * 3.4)}`;
  return [rond(12, 12, 9), `M${f(12 - dx * 5)} ${f(12 - dy * 5)}L${f(tx)} ${f(ty)}`, `M${bout(r + Math.PI * 0.8)}L${f(tx)} ${f(ty)}L${bout(r - Math.PI * 0.8)}`];
};

